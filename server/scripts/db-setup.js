const fs = require("node:fs");
const path = require("node:path");
const { randomBytes } = require("node:crypto");
const dotenv = require("dotenv");

const envPath = path.join(__dirname, "../.env");
const existing = fs.existsSync(envPath) ? fs.readFileSync(envPath, "utf8") : "";
const env = dotenv.parse(existing);
const databaseKeys = ["POSTGRES_PASSWORD", "POSTGRES_APP_PASSWORD", "DATABASE_ADMIN_URL", "DATABASE_URL"];

if (databaseKeys.some((key) => env[key])) {
  if (databaseKeys.every((key) => env[key])) {
    console.log("Database settings already exist; left unchanged.");
  } else {
    console.error("Partial database settings already exist in server/.env. Complete them using .env.example; no values were changed.");
    process.exitCode = 1;
  }
} else {
  const ownerPassword = randomBytes(32).toString("hex");
  const appPassword = randomBytes(32).toString("hex");
  const settings = {
    POSTGRES_PASSWORD: ownerPassword,
    POSTGRES_APP_PASSWORD: appPassword,
    DATABASE_ADMIN_URL: `postgresql://repopulse_owner:${ownerPassword}@localhost:5433/repopulse`,
    DATABASE_URL: `postgresql://repopulse_app:${appPassword}@localhost:5433/repopulse`,
  };
  const block = Object.entries(settings).map(([key, value]) => `${key}=${value}`).join("\n");
  // Append only generated database settings, preserving existing OAuth credentials and comments.
  fs.appendFileSync(envPath, `\n# Local PostgreSQL settings (generated by db:setup)\n${block}\n`, { mode: 0o600 });
  console.log("Added local database settings to server/.env. Existing settings were preserved; no credentials printed.");
}
